# 2. КЛАССЫ ПРЕДМЕТОВ УРОВНЯ
#    Родитель: GameObject.  Дети: Block, Spike, Portal
#
#    Идея: у блока, шипа и портала много общего - у каждого есть
#    прямоугольник, и каждого надо уметь рисовать со сдвигом камеры.
#    Чтобы не писать одно и то же трижды, это общее пишем ОДИН раз в
#    родителе, а дети берут его "в наследство".
# ==================================================================
class GameObject:
    """Родитель: любой предмет в уровне - это прямоугольник (rect)."""

    # __init__ - "рождение" объекта. Запускается сам, когда мы создаём
    # предмет, например GameObject(100, 200, 50, 50).
    # self - это "сам предмет, о котором речь".
    # x, y - где он стоит, width, height - какой он ширины и высоты.
    def __init__(self, x, y, width, height):
        # Создаём прямоугольник и прячем его в предмете под именем rect.
        # Дальше везде, где увидишь block.rect или portal.rect - это он.
        # Его используют для проверки столкновений и для рисования.
        self.rect = pygame.Rect(x, y, width, height)

    # draw - нарисовать предмет. Параметры:
    # screen - на чём рисуем, camera_x - на сколько сдвинута камера.
    def draw(self, screen, camera_x):
        # КАМЕРА. Предмет живёт в МИРЕ на своём месте, например x = 3000.
        # Но на экран мы видим только кусочек мира шириной 900.
        # Чтобы получить место на ЭКРАНЕ, сдвигаем предмет влево на camera_x.
        # move(-camera_x, 0) = "подвинь влево на camera_x и вверх-вниз на 0".
        # Именно из-за этого уровень "едет" мимо нас!
        screen_rect = self.rect.move(-camera_x, 0)

        # Если предмет целиком левее экрана (right < 0) или целиком правее
        # (left > WIDTH), он нам не виден - рисовать его не нужно.
        # Это экономит силы компьютера: рисуем только видимое.
        if screen_rect.right < 0 or screen_rect.left > WIDTH:
            # return = "выйти из функции прямо сейчас", дальше ничего не делаем
            return

        # Предмет виден - просим его нарисовать СВОЮ форму.
        # Хитрость: тут вызовется draw_shape именно того ребёнка, который
        # сейчас работает. У блока - свой, у шипа - свой, у портала - свой.
        self.draw_shape(screen, screen_rect)

    # Запасной вариант рисования (белый прямоугольник).
    # Дети его ПЕРЕОПРЕДЕЛЯЮТ - пишут свой метод с таким же именем.
    def draw_shape(self, screen, screen_rect):
        """Каждый ребёнок переопределяет этот метод и рисует себя по-своему."""
        # Рисуем белый прямоугольник на экране в месте screen_rect.
        pygame.draw.rect(screen, WHITE, screen_rect)


# (GameObject) в скобках означает: "Block - ребёнок GameObject".
# Block автоматически умеет всё, что умеет GameObject: у него есть rect
# и метод draw. Нам остаётся только сказать, КАК блок выглядит.
class Block(GameObject):
    """Кусок потолка или пола в туннеле."""

    # Переопределяем draw_shape: теперь блоки рисуются красиво.
    # (Метод draw в родителе сам его вызывает - см. выше.)
    def draw_shape(self, screen, screen_rect):
        # Сначала закрашиваем весь блок синим цветом.
        pygame.draw.rect(screen, WALL_COLOR, screen_rect)
        # Потом поверх рисуем светлую рамку толщиной 3 точки.
        # Последнее число "3" = толщина линии (без него рисуется заливка).
        pygame.draw.rect(screen, EDGE_COLOR, screen_rect, 3)


class Spike(GameObject):
    """Шип. Стоит на земле. Хитбокс меньше картинки - так честнее."""

    # У шипа свой __init__: нужен только x, потому что остальное известно:
    # шип всегда стоит на земле и всегда одного размера.
    def __init__(self, x):
        # super() = "обратиться к РОДИТЕЛЮ". Здесь мы запускаем __init__
        # родителя, и он создаёт self.rect (шип ставится НА землю:
        # его верх - это GROUND_Y минус высота шипа).
        super().__init__(x, GROUND_Y - SPIKE_SIZE, SPIKE_SIZE, SPIKE_SIZE)

        # ХИТБОКС - невидимый прямоугольник, по которому проверяем смерть.
        # Он МЕНЬШЕ картинки: у треугольника по бокам пустота, и было бы
        # нечестно умирать, коснувшись пустоты. Поэтому отступаем:
        # 9 точек от краёв по бокам и 12 точек сверху.
        self.hitbox = pygame.Rect(x + 9, GROUND_Y - SPIKE_SIZE + 12,
                                  SPIKE_SIZE - 18, SPIKE_SIZE - 12)

    # Шип рисует себя красным треугольником.
    def draw_shape(self, screen, screen_rect):
        # polygon = рисуем многоугольник по списку точек. У треугольника 3 точки:
        pygame.draw.polygon(screen, SPIKE_COLOR, [
            # левый нижний угол прямоугольника,
            screen_rect.bottomleft,
            # правый нижний угол,
            screen_rect.bottomright,
            # и середина верхней стороны - это острый кончик шипа.
            screen_rect.midtop,
        ])


class Portal(GameObject):
    """Портал. kind = "wave" / "cube" / "finish"."""

    # Портал создаётся так: Portal(x, "wave"). kind - его вид.
    def __init__(self, x, kind):
        # Родитель создаёт rect: стоит в точке x, от самого верха (y=0),
        # шириной 40 и высотой до земли (GROUND_Y) - как высокие ворота.
        super().__init__(x, 0, 40, GROUND_Y)
        # Запоминаем вид портала. В главном цикле по нему решим,
        # кем становиться: кубом, волной или это финиш.
        self.kind = kind

    def draw_shape(self, screen, screen_rect):
        # Берём цвет из шпаргалки PORTAL_COLORS по виду портала.
        color = PORTAL_COLORS[self.kind]

        # Пульсация. get_ticks() - сколько миллисекунд прошло с запуска игры.
        # sin() превращает растущее время в качели: то +1, то -1, то снова +1.
        # Умножаем на 8: портал то расширяется, то сужается на 8 точек.
        pulse = 8 * math.sin(pygame.time.get_ticks() / 150)

        # ellipse = овал. inflate(pulse, 0) = "сделай прямоугольник шире на pulse".
        # Число 6 - толщина цветной линии овала.
        pygame.draw.ellipse(screen, color, screen_rect.inflate(pulse, 0), 6)

        # Второй, белый овал поменьше внутри (inflate с минусом - СЖИМАЕТ).
        # Толщина линии 2. Он пульсирует в противоположную сторону.
        pygame.draw.ellipse(screen, WHITE, screen_rect.inflate(-24 - pulse, -40), 2)



