# 3. КЛАССЫ ИГРОКА
#    Родитель: Player.  Дети: Cube и Wave
#
#    В GD ты можешь быть кубиком, кораблём, волной... У всех есть общее
#    (бегут вправо, у всех есть размер), но двигаются по-разному.
#    Общее - в родителе Player. Особенное - в детях.
# ==================================================================
class Player:
    """Родитель: то, что одинаково у куба и у волны."""

    # Рождение игрока: запоминаем, где он стоит в мире.
    def __init__(self, x, y):
        self.x = x   # координата по горизонтали (в МИРЕ, а не на экране)
        self.y = y   # координата по вертикали (0 - верх экрана)

    # hitbox() - прямоугольник игрока для проверки столкновений.
    # Мы делаем его чуть меньше квадрата (на 4 точки со всех сторон),
    # чтобы игра прощала мелкие касания краем. Это "добрый хитбокс".
    def hitbox(self):
        # Rect(x, y, ширина, высота): сдвигаемся на 4 внутрь,
        # поэтому ширина и высота меньше на 8 (по 4 с каждой стороны).
        return pygame.Rect(self.x + 4, self.y + 4, SIZE - 8, SIZE - 8)

    # update = "обновить". Вызывается КАЖДЫЙ кадр из главного цикла.
    # dt - сколько секунд прошло с прошлого кадра, pressing - нажата ли кнопка.
    # Родитель сам кнопку не использует, но дети используют -
    # поэтому параметр есть у всех (у всех одинаковый "вид" метода).
    def update(self, dt, pressing):
        # Скорость x время = расстояние. SPEED * dt = сколько точек
        # пробежали за этот кадр. Умножение на dt делает скорость
        # одинаковой на быстром и на медленном компьютере.
        self.x += SPEED * dt

    # Простое рисование квадрата. Дети его заменят на своё.
    def draw(self, screen, camera_x):
        # Квадрат на ЭКРАНЕ: x мы сдвигаем камерой (как у предметов).
        rect = pygame.Rect(self.x - camera_x, self.y, SIZE, SIZE)
        # Жёлтая заливка...
        pygame.draw.rect(screen, PLAYER_COLOR, rect)
        # ...и чёрная рамка толщиной 3 точки.
        pygame.draw.rect(screen, (0, 0, 0), rect, 3)


class Cube(Player):
    """Куб: бежит по земле и прыгает."""

    def __init__(self, x, y):
        # Сначала пусть родитель запишет x и y (self.x и self.y).
        super().__init__(x, y)          # super() - вызываем __init__ родителя

        # Вертикальная скорость. Минус - летим вверх, плюс - падаем вниз.
        self.speed_y = 0
        # Стоим ли на земле. Нужно, чтобы нельзя было прыгать в воздухе.
        self.on_ground = False
        # На сколько градусов повёрнут квадрат. В прыжке он будет крутиться.
        self.angle = 0

        # Заранее делаем картинку-квадрат: мы будем её поворачивать.
        # Делаем это один раз, а не каждый кадр - так быстрее.
        # Surface - пустая картинка нужного размера.
        self.image = pygame.Surface((SIZE, SIZE))
        # Заливаем её жёлтым...
        self.image.fill(PLAYER_COLOR)
        # ...и рисуем чёрную рамку по краю (get_rect() - прямоугольник картинки).
        pygame.draw.rect(self.image, (0, 0, 0), self.image.get_rect(), 3)

    # Свой update у куба. Сначала делаем то, что умеет родитель, потом своё.
    def update(self, dt, pressing):
        # Запускаем update родителя: куб сдвинулся вправо.
        super().update(dt, pressing)    # сначала то, что делает родитель: бежим вправо

        # ПРЫЖОК: кнопка нажата И стоим на земле (оба условия сразу - "and").
        if pressing and self.on_ground:     # нажали и стоим на земле - прыгаем
            # Даём скорость вверх. Вверх - это минус, ведь y=0 наверху.
            self.speed_y = -JUMP_SPEED
            # Мы оторвались от земли.
            self.on_ground = False

        # ПРИТЯЖЕНИЕ: каждый кадр прибавляем скорость вниз.
        # Сначала куб летит вверх, скорость падает, доходит до нуля (верх дуги),
        # потом растёт вниз. Так получается красивая дуга прыжка.
        self.speed_y += GRAVITY * dt        # притяжение тянет вниз

        # Сдвигаем куб по вертикали на (скорость x время).
        self.y += self.speed_y * dt

        # self.y - ВЕРХ куба. self.y + SIZE - его НИЗ (подошва).
        # Если подошва достигла земли или ушла ниже - мы приземлились.
        if self.y + SIZE >= GROUND_Y:       # приземлились
            # Ставим куб точно на землю (не даём провалиться).
            self.y = GROUND_Y - SIZE
            # Падать больше некуда - скорость ноль.
            self.speed_y = 0
            # Снова можно прыгать.
            self.on_ground = True
            # Выравниваем поворот до ближайших 90 градусов (0, 90, 180...),
            # чтобы куб красиво встал на землю ровно.
            self.angle = round(self.angle / 90) * 90    # выравниваем квадрат
        else:
            # Мы в воздухе - куб крутится: 450 градусов в секунду.
            self.angle += 450 * dt                      # крутимся в воздухе

    # Проверка: погиб ли куб? Главный цикл спрашивает об этом каждый кадр.
    # blocks кубу не нужны, но параметр оставляем: у Wave такой же метод,
    # а главный цикл вызывает их ОДИНАКОВО (это называется полиморфизм).
    def is_dead(self, spikes, blocks):
        """Куб погибает только от шипов."""
        # Перебираем шипы по одному...
        for spike in spikes:
            # colliderect = "пересекаются ли два прямоугольника?"
            # Сравниваем хитбокс куба с хитбоксом шипа.
            if self.hitbox().colliderect(spike.hitbox):
                # Коснулись шипа - погибли. True = "да, погиб".
                return True
        # Все шипы проверили, не коснулись ни одного - живы. False = "нет".
        return False

    # Куб рисуется повёрнутым - значит, заменяем рисование родителя.
    def draw(self, screen, camera_x):
        # Поворачиваем нашу картинку-квадрат. Минус нужен, потому что pygame
        # крутит против часовой стрелки, а нам нужно по часовой.
        rotated = pygame.transform.rotate(self.image, -self.angle)
        # Центр куба на экране (с учётом камеры).
        center = (self.x - camera_x + SIZE / 2, self.y + SIZE / 2)
        # blit = "приклеить картинку на экран". Повёрнутая картинка получается
        # больше, поэтому ставим её по ЦЕНТРУ, а не по углу, иначе куб "поплывёт".
        screen.blit(rotated, rotated.get_rect(center=center))


class Wave(Player):
    """Волна: летит по диагонали - вверх или вниз."""

    def __init__(self, x, y):
        # Родитель запишет x и y.
        super().__init__(x, y)
        # След за волной: список точек, где волна недавно была.
        self.trail = []                 # след за волной

    def update(self, dt, pressing):
        # Бежим вправо (родитель).
        super().update(dt, pressing)    # бежим вправо

        # У волны всё просто: кнопка нажата - вверх, отпущена - вниз.
        # Вверх - это уменьшать y, вниз - увеличивать y.
        if pressing:
            self.y -= WAVE_SPEED * dt   # держим кнопку - вверх
        else:
            self.y += WAVE_SPEED * dt   # отпустили - вниз

        # Запоминаем центр квадрата в конец списка следа.
        # append = "добавить в конец списка".
        self.trail.append((self.x + SIZE / 2, self.y + SIZE / 2))
        # Если точек стало больше 25 - выкидываем самую старую (из начала).
        # Так след всегда короткий, и память не растёт без конца.
        if len(self.trail) > 25:        # храним только 25 последних точек
            self.trail.pop(0)

    # Волна умирает не от шипов, а от земли, верха экрана и блоков.
    def is_dead(self, spikes, blocks):
        """Волна погибает от земли, верха экрана и блоков."""
        # Если вылетели выше экрана (y < 0) или коснулись земли
        # (низ квадрата глубже GROUND_Y) - погибли.
        if self.y < 0 or self.y + SIZE > GROUND_Y:
            return True
        # Теперь проверяем каждый блок потолка и пола.
        for block in blocks:
            # Хитбокс волны пересёкся с прямоугольником блока - погибли.
            if self.hitbox().colliderect(block.rect):
                return True
        # Ни во что не врезались - живы.
        return False

    def draw(self, screen, camera_x):
        # Рисуем след: перебираем точки по номерам, начиная со второй.
        # range(1, len(...)) = числа 1, 2, 3... до конца списка.
        for i in range(1, len(self.trail)):
            # Берём пару соседних точек: предыдущую (i-1) и текущую (i).
            # [0] - это x точки, [1] - её y. Вычитаем камеру из x.
            start = (self.trail[i - 1][0] - camera_x, self.trail[i - 1][1])
            end = (self.trail[i][0] - camera_x, self.trail[i][1])
            # Соединяем их линией. Толщина i // 4: чем новее точка (больше i),
            # тем линия толще - получается хвост-комета. max(1, ...) гарантирует,
            # что толщина будет не меньше 1.
            pygame.draw.line(screen, PLAYER_COLOR, start, end, max(1, i // 4))
        # После следа рисуем сам квадрат - так, как умеет родитель.
        super().draw(screen, camera_x)  # а потом рисуем сам квадрат, как у родителя


# ==================================================================
# 4. УРОВЕНЬ
#    Уровень - это три списка: шипы, блоки и порталы.
#    Функции add_ground и add_wave наполняют эти списки, как конструктор.
# ==================================================================

# Три пустых списка (коробки). Сюда будем складывать предметы уровня.
# Позже главный цикл будет перебирать их: проверять смерть и рисовать.
spikes = []     # все шипы
blocks = []     # все блоки потолка и пола
portals = []    # порталы смены режима


# Функция строит участок земли и возвращает, где он закончился.
# x - где участок начинается, length - его длина,
# spike_offsets - список "через сколько точек от начала стоит каждый шип".
def add_ground(x, length, spike_offsets):
    """Участок земли. spike_offsets - на каком расстоянии от начала стоят шипы.
    Возвращает x, где участок заканчивается."""
    # В самом начале уровня (x = 0) портал не нужен - мы и так кубом.
    # А в остальных местах земля начинается после туннеля, значит,
    # нужен оранжевый портал "снова становимся кубом".
    if x > 0:
        # append - кладём в список новый портал.
        portals.append(Portal(x, "cube"))
    # Для каждого числа из списка делаем шип и кладём в список spikes.
    for offset in spike_offsets:
        # Шип стоит на расстоянии offset ОТ НАЧАЛА участка: x + offset.
        spikes.append(Spike(x + offset))
    # Возвращаем, где участок закончился. Это число станет началом следующего.
    return x + length


# Функция строит туннель для волны из ступенек.
def add_wave(x, steps):
    """Туннель для волны. Каждая ступенька - пара (потолок, пол):
    потолок - где он заканчивается сверху (0 - потолка нет),
    пол     - где он начинается снизу (500 - обычная земля).
    Возвращает x, где туннель заканчивается."""
    # В начале туннеля ставим фиолетовый портал "становимся волной".
    portals.append(Portal(x, "wave"))
    # Перебираем ступеньки. В каждой лежит пара: (ceiling, floor).
    # Python сам раскладывает пару на две переменные - это удобно.
    for ceiling, floor in steps:
        # Потолок = 0 означает "потолка нет". Если он есть (больше 0) -
        # ставим блок от самого верха экрана (y = 0) вниз на ceiling точек.
        if ceiling > 0:
            blocks.append(Block(x, 0, STEP_WIDTH, ceiling))
        # Если пол выше земли (floor < GROUND_Y), ставим блок: он начинается
        # в точке floor и идёт вниз до земли (высота = GROUND_Y - floor).
        if floor < GROUND_Y:
            blocks.append(Block(x, floor, STEP_WIDTH, GROUND_Y - floor))
        # Сдвигаемся вправо на ширину ступеньки - к следующей.
        x += STEP_WIDTH
    # Возвращаем, где туннель закончился.
    return x


# Туннели записаны как списки пар (потолок, пол). Каждая пара - одна ступенька.
# Пример: (120, 420) - потолок опускается до 120, пол начинается с 420,
# значит, проход между ними 300 точек. (0, 500) = всё открыто.
# Чем меньше проход (пол минус потолок), тем сложнее пролететь!
# Меняй числа - получишь свой уровень!
WAVE_1 = [(0, 500), (0, 500), (120, 420), (40, 340), (140, 440),
          (60, 300), (180, 440), (100, 320), (0, 500), (0, 500)]

WAVE_2 = [(0, 500), (0, 500), (80, 360), (200, 480), (120, 330),
          (40, 260), (100, 360), (180, 420), (0, 500), (0, 500)]

# Третий и четвёртый туннели: они длиннее (по 12 ступенек) и сложнее -
# проходы местами уже. Чем дальше по уровню, тем труднее, как в GD!
WAVE_3 = [(0, 500), (0, 500), (100, 380), (200, 470), (130, 340),
          (30, 250), (90, 330), (170, 450), (80, 300), (150, 400),
          (0, 500), (0, 500)]

WAVE_4 = [(0, 500), (0, 500), (160, 400), (70, 300), (170, 380),
          (110, 300), (40, 230), (110, 320), (200, 420), (130, 330),
          (0, 500), (0, 500)]

# ---------- Собираем уровень по кусочкам, как конструктор ----------
# x - "курсор": место, куда мы сейчас строим. Сначала в начале мира.
x = 0
# Строим землю длиной 1500 с четырьмя шипами (на 600, 900, 960 и 1250
# от начала). Функция вернёт, где земля кончилась, - кладём это в x.
x = add_ground(x, 1500, [600, 900, 960, 1250])
# Туннель WAVE_1 стартует там, где кончилась земля. И снова обновляем x.
x = add_wave(x, WAVE_1)
# Снова земля, но уже с другими шипами.
x = add_ground(x, 1300, [450, 510, 850, 1050])
# Второй туннель.
x = add_wave(x, WAVE_2)
# Ещё один участок земли (длина 1200) - между вторым и третьим туннелем.
x = add_ground(x, 1200, [400, 460, 800, 1000])
# Третий туннель.
x = add_wave(x, WAVE_3)
# Земля подлиннее (1400) с одним двойным шипом и одним одиночным.
x = add_ground(x, 1400, [400, 700, 760, 1100])
# Четвёртый, самый сложный туннель.
x = add_wave(x, WAVE_4)
# Финальный участок земли: три группы шипов, а потом зелёный финиш.
x = add_ground(x, 1400, [350, 410, 750, 1000, 1060])
# Запоминаем, где уровень закончился (последнее значение x).
# level_end нужен для полоски прогресса и для финиша.
level_end = x
# Зелёный портал-финиш в самом конце. Коснулись его - победа.
finish = Portal(level_end, "finish")


# ==================================================================
# 5. ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
#    Маленькие помощники, чтобы главный цикл был чище.
# ==================================================================

# Отвечает на вопрос "игрок сейчас нажимает кнопку управления?"
def is_pressing():
    """Нажата ли хоть одна кнопка управления?"""
    # keys - состояние ВСЕХ клавиш клавиатуры прямо сейчас.
    keys = pygame.key.get_pressed()
    # mouse - состояние кнопок мыши (три значения: левая, средняя, правая).
    mouse = pygame.mouse.get_pressed()
    # "or" = "или". Результат "да", если зажат пробел ИЛИ стрелка вверх
    # ИЛИ левая кнопка мыши (mouse[0] - левая кнопка).
    # Результат уходит в player.update(...) в главном цикле.
    return keys[pygame.K_SPACE] or keys[pygame.K_UP] or mouse[0]


# Пишет текст на экране. Параметры: что писать, каким шрифтом, на какой высоте,
# каким цветом (по умолчанию белым) и в какой точке по горизонтали
# (по умолчанию - посередине экрана).
def draw_text(text, text_font, y, color=WHITE, x=WIDTH // 2):
    """Пишет текст по центру (по горизонтали) на высоте y."""
    # render превращает слова в картинку. True делает буквы гладкими.
    image = text_font.render(text, True, color)
    # Приклеиваем картинку на экран. Берём её прямоугольник и ставим его
    # ЦЕНТРОМ в точку (x, y) - так текст ровно по центру нужной точки.
    screen.blit(image, image.get_rect(center=(x, y)))


# ==================================================================
# 6. ГЛАВНЫЙ ЦИКЛ ИГРЫ
#    Всё, что мы написали выше, - подготовка. Здесь игра ОЖИВАЕТ.
#    Цикл повторяется 60 раз в секунду. Каждый такой повтор = один кадр:
#       1) смотрим, что нажал игрок
#       2) двигаем всё и проверяем столкновения
#       3) рисуем новую картинку
# ==================================================================

# Игра начинается с КУБА, который стоит на земле:
# y = GROUND_Y - SIZE, значит подошва точно на уровне земли.
player = Cube(START_X, GROUND_Y - SIZE)   # игра начинается с куба на земле

# Номер попытки (как в GD: "Попытка 15").
attempt = 1                               # номер попытки

# Состояние игры - одно из трёх слов:
#   "playing" - играем,  "dead" - разбились,  "won" - победили.
# От него зависит, двигается ли игра и какой текст рисовать.
state = "playing"                         # "playing" (играем), "dead" (разбились), "won" (победа)

# "while True" значит "пока правда" - а правда всегда, поэтому цикл вечный.
# Выйти из него можно только командой sys.exit() (см. ниже).
while True:
    # clock.tick(FPS) подождёт, чтобы кадров было не больше 60 в секунду,
    # и скажет, сколько миллисекунд прошло с прошлого кадра.
    # Делим на 1000, чтобы получить секунды. Это и есть dt.
    # dt передаётся в player.update(dt, ...), и от него зависит скорость.
    dt = clock.tick(FPS) / 1000           # сколько секунд прошло с прошлого кадра

    # ---------- 1. СОБЫТИЯ (что сделал игрок) ----------
    # pygame собирает "события": закрыли окно, нажали клавишу и т.д.
    # Перебираем их все по очереди.
    for event in pygame.event.get():
        # Нажали крестик окна - закрываем игру.
        if event.type == pygame.QUIT:
            # Выключаем pygame...
            pygame.quit()
            # ...и завершаем программу (так мы выходим из вечного цикла).
            sys.exit()
        # Нажали какую-то клавишу (KEYDOWN = "клавишу опустили").
        if event.type == pygame.KEYDOWN:
            # Escape - тоже выход.
            if event.key == pygame.K_ESCAPE:
                pygame.quit()
                sys.exit()
            # R работает только когда игра НЕ идёт (разбились или победили).
            # "!=" значит "не равно".
            if event.key == pygame.K_r and state != "playing":
                # Если разбились, то это новая попытка: +1 к счётчику.
                # (После победы счётчик не растёт.)
                if state == "dead":
                    attempt += 1
                # Всё заново: новый куб на старте. Старый объект player
                # просто заменяется новым - шипы, блоки и порталы остаются.
                player = Cube(START_X, GROUND_Y - SIZE)   # всё заново
                # И снова играем.
                state = "playing"

    # ---------- 2. ОБНОВЛЯЕМ ИГРУ (двигаем, проверяем) ----------
    # Двигаем игру только если сейчас играем. После смерти всё замирает.
    if state == "playing":
        # Запоминаем, где игрок был ДО движения. Пригодится для порталов.
        previous_x = player.x

        # Игрок делает шаг. Python сам определит, кто сейчас player:
        # Cube.update (прыжок и притяжение) или Wave.update (вверх-вниз).
        # is_pressing() возвращает "нажата ли кнопка" - это pressing в update.
        player.update(dt, is_pressing())   # куб и волна обновляются каждый по-своему!

        # ПОРТАЛЫ. Перебираем все порталы...
        for portal in portals:
            # Проверяем, ПЕРЕСЕКЛИ ли мы портал в этот кадр:
            # раньше мы были левее него (previous_x < portal.rect.x),
            # а теперь на нём или правее (portal.rect.x <= player.x).
            # Запись a < b <= c проверяет оба условия сразу.
            if previous_x < portal.rect.x <= player.x:
                # Фиолетовый портал - становимся волной. Старый объект player
                # заменяем НОВЫМ объектом Wave (на той же позиции x).
                # Новую волну ставим по центру высоты, чтобы не упала в землю.
                if portal.kind == "wave":
                    player = Wave(player.x, GROUND_Y / 2 - SIZE / 2)
                # Иначе (оранжевый портал) становимся кубом: берём тот же x и y,
                # и дальше куб сам упадёт на землю под притяжением.
                else:
                    player = Cube(player.x, player.y)

        # Проверка смерти. Опять полиморфизм: нам неважно, куб это или волна,
        # у обоих есть метод is_dead, и каждый проверяет по-своему.
        if player.is_dead(spikes, blocks):
            # Погибли - меняем состояние. Тогда блок "if state == playing"
            # выше перестанет двигать игру, и появится надпись "Разбился!".
            state = "dead"
        # elif = "а если не погибли, то проверим ещё вот что":
        # хитбокс игрока пересёкся с финишем? Тогда победа!
        elif player.hitbox().colliderect(finish.rect):
            state = "won"

    # ---------- 3. РИСУЕМ (всё, что видит игрок) ----------
    # КАМЕРА: игрок всегда стоит на экране в точке PLAYER_SCREEN_X.
    # Значит, камера отстаёт от него ровно на это расстояние.
    # camera_x уйдёт в draw всех предметов и вычтется из их x.
    camera_x = player.x - PLAYER_SCREEN_X     # камера следует за игроком

    # Сначала закрашиваем весь экран цветом фона - это стирает прошлый кадр.
    # Без этого картинки наложились бы друг на друга, как в сломанной игре.
    screen.fill(BG_COLOR)

    # Земля - широкий синий прямоугольник снизу экрана.
    # Параметры: (x, y, ширина, высота): от GROUND_Y и до низа окна.
    pygame.draw.rect(screen, WALL_COLOR, (0, GROUND_Y, WIDTH, HEIGHT - GROUND_Y))
    # Светлая линия поверх - поверхность земли.
    pygame.draw.line(screen, EDGE_COLOR, (0, GROUND_Y), (WIDTH, GROUND_Y), 3)

    # Рисуем все блоки: перебираем список и просим каждого нарисоваться.
    # Каждый сам решит, виден ли он, и нарисует свою форму (см. GameObject).
    for block in blocks:
        block.draw(screen, camera_x)
    # Рисуем все шипы.
    for spike in spikes:
        spike.draw(screen, camera_x)
    # Рисуем все порталы смены режима.
    for portal in portals:
        portal.draw(screen, camera_x)
    # Рисуем финиш. Он один, поэтому без цикла.
    finish.draw(screen, camera_x)
    # Рисуем игрока ПОСЛЕДНИМ, чтобы он был поверх всего остального.
    # Нарисуется то, чем мы сейчас являемся: куб или волна.
    player.draw(screen, camera_x)             # рисует либо куб, либо волну

    # ---------- Полоска прогресса ----------
    # Сколько процентов уровня пройдено: пройденный путь делим на длину
    # всего пути и умножаем на 100.
    percent = (player.x - START_X) / (level_end - START_X) * 100
    # Ограничиваем от 0 до 100 (max не даёт уйти ниже 0, min - выше 100)
    # и убираем дробную часть (int).
    percent = max(0, min(100, int(percent)))
    # Серая полоска-фон: x=150, y=15, ширина WIDTH-300, высота 14,
    # со скруглёнными краями (border_radius).
    pygame.draw.rect(screen, (60, 60, 90), (150, 15, WIDTH - 300, 14), border_radius=7)
    # Зелёная заполненная часть: ширина = полная ширина x процент / 100.
    # Если percent = 50, закрашена ровно половина полоски.
    pygame.draw.rect(screen, PORTAL_COLORS["finish"],
                     (150, 15, (WIDTH - 300) * percent / 100, 14), border_radius=7)
    # Число процентов справа от полоски. f"..." - строка, в которую
    # можно вставить переменную в фигурных скобках {percent}.
    draw_text(f"{percent}%", font, 22, x=WIDTH - 75)
    # Номер попытки в левом углу.
    draw_text(f"Попытка {attempt}", font, 55, x=100)

    # ---------- Надписи после конца игры ----------
    # Если разбились - красная надпись и подсказка.
    if state == "dead":
        draw_text("Разбился!", big_font, HEIGHT // 2 - 40, (255, 80, 80))
        draw_text("Нажми R, чтобы попробовать снова", font, HEIGHT // 2 + 20)
    # Если победили - зелёная надпись. {attempt} вставит число попыток.
    elif state == "won":
        draw_text("Уровень пройден!", big_font, HEIGHT // 2 - 40, PORTAL_COLORS["finish"])
        draw_text(f"Попыток: {attempt}.  R - сыграть ещё раз", font, HEIGHT // 2 + 20)

    # ГЛАВНЫЙ МОМЕНТ: до этого мы рисовали "за кулисами", в невидимой копии.
    # flip() выкладывает готовую картинку в окно - игрок видит новый кадр.
    # Потом цикл возвращается к началу, и всё повторяется 60 раз в секунду.
    pygame.display.flip()
